export function notebookRoles(preset) {
  const mix = (color, weight, base = preset.surface) => `color-mix(in srgb, ${color} ${weight}%, ${base})`;
  return {
    page: preset.color,
    card: preset.surface,
    ink: preset.text,
    accent: preset.accent,
    'on-accent': '#fffaf0',
    panel: mix(preset.color, 40),
    control: mix(preset.color, 28),
    line: mix(preset.border, 55),
    'line-strong': mix(preset.border, 85),
    hover: mix(preset.accent, 10),
    selected: mix(preset.accent, 15),
    pressed: mix(preset.accent, 23),
    muted: mix(preset.text, 78, preset.color),
    success: preset.success,
    'success-wash': mix(preset.success, 10),
    danger: preset.danger,
    'danger-wash': mix(preset.danger, 12),
    reminder: mix(preset.warm, 12),
    leaf: mix(preset.stem, 8),
  };
}
